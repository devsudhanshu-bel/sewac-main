const helperPrisma =
  require("../config/helperPrisma");

const masterCitizenPrisma =
  require("../config/masterCitizenPrisma");


// =====================================================
// CONFIGURATION
// =====================================================

const DEFAULT_BATCH_SIZE = 5000;


// =====================================================
// SAFE SQL IDENTIFIER
// =====================================================
//
// Dynamic table names are being used throughout the
// Master Citizen hierarchy.
//
// Example:
//
// city table:
//     bangalore_city
//
// zone table:
//     bangalore_east_zone
//
// division table:
//     bangalore_east_division
//
// ward table:
//     ward_ibbaluru
//
// Since these are identifiers rather than values,
// Prisma parameters cannot be used directly for the
// table name.
//
// This validation prevents malformed identifiers from
// being inserted into raw SQL.
// =====================================================

function validateTableName(
  tableName
) {
  if (
    typeof tableName !== "string" ||
    !tableName.trim()
  ) {
    throw new Error(
      `Invalid dynamic table name: ${tableName}`
    );
  }

  const trimmed =
    tableName.trim();

  //
  // PostgreSQL identifiers generated by our system
  // should contain letters, numbers and underscores.
  //

  if (
    !/^[A-Za-z0-9_]+$/.test(trimmed)
  ) {
    throw new Error(
      `Unsafe dynamic table name: ${trimmed}`
    );
  }

  return trimmed;
}


// =====================================================
// NORMALIZE WARD NUMBER
// =====================================================
//
// Handles:
//
// 216
// "216"
// "Ward 216"
// "WARD 216"
// "ward-216"
// "Ibbaluru-216"
//
// Returns:
//
// 216
//
// or:
//
// null
// =====================================================

function normalizeWardNumber(
  wardValue
) {
  if (
    wardValue === null ||
    wardValue === undefined
  ) {
    return null;
  }

  const value =
    String(wardValue).trim();

  if (!value) {
    return null;
  }

  //
  // Pure numeric value
  //

  if (
    /^\d+$/.test(value)
  ) {
    const number =
      Number(value);

    return Number.isInteger(number)
      ? number
      : null;
  }

  //
  // Extract first numeric sequence
  //

  const match =
    value.match(/\d+/);

  if (!match) {
    return null;
  }

  const number =
    Number(match[0]);

  return Number.isInteger(number)
    ? number
    : null;
}


// =====================================================
// GET CITIZENS FROM HELPER DATABASE
// =====================================================
//
// Source:
//
// Helper DB
//     ↓
// master_citizen_data
//
// The `ward` field is used only for routing.
//
// It is NOT inserted into the dynamic Ward table.
//
// Pagination:
//
// skip / take
//
// Default:
//
// 5000 records per batch
// =====================================================

async function getHelperCitizens(
  skip = 0,
  take = DEFAULT_BATCH_SIZE
) {
  return helperPrisma.master_citizen_data.findMany({

    skip,

    take,

    orderBy: {
      id: "asc",
    },

    select: {

      id: true,

      phoneNumber: true,

      //
      // Used only by the sync service to determine
      // the destination Ward.
      //
      ward: true,

      area: true,

      wasteGeneratorTypes: true,

      houseNumber: true,

      floorNumber: true,

      householdType: true,

      personName: true,

      contactNumber: true,

      numberOfPeople: true,

      buildingPhoto: true,

      createdAt: true,

      updatedAt: true,

      dryRFID: true,

      drySlno: true,

      wetRFID: true,

      wetSlno: true,

      lat: true,

      lng: true,
    },
  });
}


// =====================================================
// GET ALL WARD MAPPINGS
// =====================================================
//
// COMPLETE MASTER CITIZEN HIERARCHY:
//
// City
//   ↓
// Zone
//   ↓
// Division
//   ↓
// Ward
//   ↓
// Dynamic Ward Citizen Table
//
// Example:
//
// Bangalore
//   ↓
// Zone 1
//   ↓
// Division A
//   ↓
// Ward 216
//   ↓
// ward_ibbaluru
//
// Result:
//
// {
//   cityId: 1,
//   cityName: "Bangalore",
//
//   zoneId: 3,
//   zoneName: "South Zone",
//
//   divisionId: 4,
//   divisionName: "Division A",
//
//   wardId: 3,
//   wardNo: 216,
//   wardName: "Ibbaluru",
//
//   wardTableName: "ward_ibbaluru"
// }
//
// =====================================================

async function getAllWardMappings() {

  console.log(
    "[Master Citizen Repository] Loading hierarchy..."
  );


  // ===================================================
  // CITY
  // ===================================================

  const cities =
    await masterCitizenPrisma.city_table.findMany({

      select: {

        city_id: true,

        city_name: true,

        city_table_name: true,
      },

      orderBy: {
        city_id: "asc",
      },
    });


  const wardMappings = [];


  // ===================================================
  // CITY LOOP
  // ===================================================

  for (
    const city of cities
  ) {

    if (
      !city.city_table_name
    ) {
      console.warn(
        `[Master Citizen Repository] City ${city.city_name} has no dynamic table`
      );

      continue;
    }


    const cityTableName =
      validateTableName(
        city.city_table_name
      );


    // =================================================
    // ZONES
    // =================================================

    const zones =
      await masterCitizenPrisma.$queryRawUnsafe(
        `
        SELECT
          zone_id,
          zone_name,
          zone_table_name
        FROM "${cityTableName}"
        ORDER BY zone_id ASC
        `
      );


    // =================================================
    // ZONE LOOP
    // =================================================

    for (
      const zone of zones
    ) {

      if (
        !zone.zone_table_name
      ) {

        console.warn(
          `[Master Citizen Repository] Zone ${zone.zone_name} has no dynamic table`
        );

        continue;
      }


      const zoneTableName =
        validateTableName(
          zone.zone_table_name
        );


      // ===============================================
      // DIVISIONS
      // ===============================================

      const divisions =
        await masterCitizenPrisma.$queryRawUnsafe(
          `
          SELECT
            division_id,
            division_name,
            division_table_name
          FROM "${zoneTableName}"
          ORDER BY division_id ASC
          `
        );


      // ===============================================
      // DIVISION LOOP
      // ===============================================

      for (
        const division of divisions
      ) {

        if (
          !division.division_table_name
        ) {

          console.warn(
            `[Master Citizen Repository] Division ${division.division_name} has no dynamic table`
          );

          continue;
        }


        const divisionTableName =
          validateTableName(
            division.division_table_name
          );


        // =============================================
        // WARDS
        // =============================================

        const wards =
          await masterCitizenPrisma.$queryRawUnsafe(
            `
            SELECT
              ward_id,
              ward_no,
              ward_name,
              ward_table_name
            FROM "${divisionTableName}"
            ORDER BY ward_id ASC
            `
          );


        // =============================================
        // WARD LOOP
        // =============================================

        for (
          const ward of wards
        ) {

          if (
            !ward.ward_table_name
          ) {

            console.warn(
              `[Master Citizen Repository] Ward ${ward.ward_name} has no dynamic table`
            );

            continue;
          }


          const wardTableName =
            validateTableName(
              ward.ward_table_name
            );


          //
          // IMPORTANT:
          //
          // PostgreSQL may return ward_no as:
          //
          // number
          //
          // OR
          //
          // string
          //
          // We normalize it here so the rest of the
          // application always receives a Number.
          //

          const normalizedWardNo =
            normalizeWardNumber(
              ward.ward_no
            );


          if (
            normalizedWardNo === null
          ) {

            console.warn(
              `[Master Citizen Repository] Invalid ward number for ${ward.ward_name}:`,
              ward.ward_no
            );

            continue;
          }


          // =========================================
          // CREATE WARD MAPPING
          // =========================================

          wardMappings.push({

            cityId:
              city.city_id,

            cityName:
              city.city_name,

            zoneId:
              zone.zone_id,

            zoneName:
              zone.zone_name,

            divisionId:
              division.division_id,

            divisionName:
              division.division_name,

            wardId:
              ward.ward_id,

            wardNo:
              normalizedWardNo,

            wardName:
              ward.ward_name,

            wardTableName:
              wardTableName,
          });
        }
      }
    }
  }


  // ===================================================
  // DEBUG SUMMARY
  // ===================================================

  console.log(
    `[Master Citizen Repository] Cities found: ${cities.length}`
  );

  console.log(
    `[Master Citizen Repository] Wards mapped: ${wardMappings.length}`
  );


  //
  // Optional useful debug output.
  //
  // This lets you immediately verify that 216 is
  // actually present.
  //

  const ward216 =
    wardMappings.find(
      (ward) =>
        ward.wardNo === 216
    );


  if (ward216) {

    console.log(
      "[Master Citizen Repository] Ward 216 mapping:",
      {
        city:
          ward216.cityName,

        zone:
          ward216.zoneName,

        division:
          ward216.divisionName,

        wardId:
          ward216.wardId,

        wardNo:
          ward216.wardNo,

        wardName:
          ward216.wardName,

        wardTableName:
          ward216.wardTableName,
      }
    );

  } else {

    console.log(
      "[Master Citizen Repository] Ward 216 not present in hierarchy"
    );
  }


  return wardMappings;
}


// =====================================================
// BULK UPSERT CITIZENS INTO WARD TABLE
// =====================================================
//
// Destination:
//
// master_citizen_db
//
// Dynamic table:
//
// ward_ibbaluru
//
// The citizen's `ward` field is NOT stored.
//
// The destination table itself represents the Ward.
//
// Example:
//
// Helper:
//
// ward = "216"
//
// ↓
//
// hierarchy:
//
// wardNo = 216
//
// ↓
//
// destination:
//
// ward_ibbaluru
//
// =====================================================

async function bulkUpsertWardCitizens(
  wardTableName,
  citizens
) {

  // ===================================================
  // VALIDATION
  // ===================================================

  if (
    !wardTableName
  ) {
    throw new Error(
      "Ward table name is required"
    );
  }


  if (
    !Array.isArray(citizens)
  ) {
    throw new Error(
      "Citizens must be an array"
    );
  }


  if (
    !citizens.length
  ) {

    return {
      insertedOrUpdated: 0,
    };
  }


  const safeWardTableName =
    validateTableName(
      wardTableName
    );


  // ===================================================
  // BUILD VALUES
  // ===================================================

  const values = [];


  for (
    const citizen of citizens
  ) {

    values.push(

      citizen.id,

      citizen.phoneNumber,

      citizen.area,

      citizen.wasteGeneratorTypes,

      citizen.houseNumber,

      citizen.floorNumber,

      citizen.householdType,

      citizen.personName,

      citizen.contactNumber,

      citizen.numberOfPeople,

      citizen.buildingPhoto,

      citizen.createdAt,

      citizen.updatedAt,

      citizen.dryRFID,

      citizen.drySlno,

      citizen.wetRFID,

      citizen.wetSlno,

      citizen.lat,

      citizen.lng
    );
  }


  // ===================================================
  // BUILD PLACEHOLDERS
  // ===================================================

  const placeholders = [];

  let parameterIndex = 1;


  for (
    let i = 0;
    i < citizens.length;
    i++
  ) {

    placeholders.push(`(
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++},
      $${parameterIndex++}
    )`);
  }


  // ===================================================
  // UPSERT QUERY
  // ===================================================

  const query = `
    INSERT INTO "${safeWardTableName}"
    (
      id,
      "phoneNumber",
      area,
      "wasteGeneratorTypes",
      "houseNumber",
      "floorNumber",
      "householdType",
      "personName",
      "contactNumber",
      "numberOfPeople",
      "buildingPhoto",
      "createdAt",
      "updatedAt",
      "dryRFID",
      "drySlno",
      "wetRFID",
      "wetSlno",
      lat,
      lng
    )

    VALUES

      ${placeholders.join(",")}

    ON CONFLICT (id)

    DO UPDATE SET

      "phoneNumber" =
        EXCLUDED."phoneNumber",

      area =
        EXCLUDED.area,

      "wasteGeneratorTypes" =
        EXCLUDED."wasteGeneratorTypes",

      "houseNumber" =
        EXCLUDED."houseNumber",

      "floorNumber" =
        EXCLUDED."floorNumber",

      "householdType" =
        EXCLUDED."householdType",

      "personName" =
        EXCLUDED."personName",

      "contactNumber" =
        EXCLUDED."contactNumber",

      "numberOfPeople" =
        EXCLUDED."numberOfPeople",

      "buildingPhoto" =
        EXCLUDED."buildingPhoto",

      "createdAt" =
        EXCLUDED."createdAt",

      "updatedAt" =
        EXCLUDED."updatedAt",

      "dryRFID" =
        EXCLUDED."dryRFID",

      "drySlno" =
        EXCLUDED."drySlno",

      "wetRFID" =
        EXCLUDED."wetRFID",

      "wetSlno" =
        EXCLUDED."wetSlno",

      lat =
        EXCLUDED.lat,

      lng =
        EXCLUDED.lng
  `;


  // ===================================================
  // EXECUTE
  // ===================================================

  await masterCitizenPrisma.$executeRawUnsafe(
    query,
    ...values
  );


  // ===================================================
  // RESULT
  // ===================================================

  return {

    insertedOrUpdated:
      citizens.length,
  };
}


